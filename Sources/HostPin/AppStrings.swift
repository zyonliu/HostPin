import Foundation

struct AppMessage: ExpressibleByStringInterpolation {
    let key: String
    let arguments: [String]

    init(stringLiteral value: String) { key = value; arguments = [] }
    init(stringInterpolation value: StringInterpolation) { key = value.key; arguments = value.arguments }

    struct StringInterpolation: StringInterpolationProtocol {
        var key = ""
        var arguments: [String] = []

        init(literalCapacity: Int, interpolationCount: Int) {
            key.reserveCapacity(literalCapacity)
            arguments.reserveCapacity(interpolationCount)
        }

        mutating func appendLiteral(_ value: String) { key += value }
        mutating func appendInterpolation<T>(_ value: T) {
            key += "%@"
            arguments.append(String(describing: value))
        }
    }
}

func L(_ message: AppMessage) -> String {
    let template = HostPinPreferences.englishEnabled ? (englishStrings[message.key] ?? message.key) : message.key
    guard !message.arguments.isEmpty else { return template }
    return String(format: template, arguments: message.arguments.map { $0 as CVarArg })
}

func localizedText(_ text: String) -> String {
    guard HostPinPreferences.englishEnabled else { return text }
    if let translation = englishStrings[text] { return translation }
    let catalogLabels = ["本地缓存": "Local cache", "已导入": "Imported", "已更新": "Updated", "使用本地快照": "Using snapshot"]
    let parts = text.components(separatedBy: " · ")
    if parts.count == 2, let label = catalogLabels[parts[0]],
       let count = parts[1].split(separator: " ").first {
        return label + " · " + count + " rules"
    }
    if parts.count >= 3, let last = parts.last, let phase = englishStrings[last] {
        return (parts.dropLast() + [phase]).joined(separator: " · ")
    }
    return text
}

